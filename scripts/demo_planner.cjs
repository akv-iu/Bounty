const assert = require('node:assert/strict');
const { readFileSync, writeFileSync } = require('node:fs');
const path = require('node:path');
const { planScenario } = require('../dist/planner/index.js');
const snapshot = JSON.parse(readFileSync(path.join(__dirname, '../data/scenario.json'), 'utf8'));

function teachingCase(name) {
  const request = structuredClone(snapshot);
  request.scenarioId = `synthetic-${name}`;
  request.provenance.mode = 'synthetic';
  for (const region of request.regions) {
    region.carbonGPerKwh.fill(region.id === 'ERCO' ? 100 : 400);
    region.priceUsdPerMwh.fill(100);
    region.availableGpus.fill(32);
    region.carbonSource = { kind: 'synthetic', label: 'Flat teaching fixture, not historical data', url: null, sha256: null };
  }
  request.jobs = [{ id: 'example', homeRegionId: 'CISO', eligibleRegionIds: ['CISO', 'ERCO'], releaseSlot: 0, deadlineSlot: 4, durationSlots: 2, gpus: 16, facilityPowerKw: 100 }];
  return request;
}

const benefit = teachingCase('geographic-benefit');
const pinned = teachingCase('pinned-urgent'); pinned.jobs[0].eligibleRegionIds = ['CISO']; pinned.jobs[0].deadlineSlot = 2;
const tradeoff = teachingCase('carbon-priority-tradeoff'); tradeoff.regions.find(r => r.id === 'ERCO').priceUsdPerMwh.fill(200);
const cost = structuredClone(tradeoff); cost.scenarioId = 'synthetic-cost-priority-tradeoff'; cost.objective = 'cost';
const saturated = teachingCase('capacity-rejection'); for (const region of saturated.regions) region.availableGpus.fill(0);
const cases = [benefit, pinned, tradeoff, cost, saturated].map(request => ({ request, result: planScenario(request) }));
assert.equal(cases[0].result.policies.regionAndTime.assignments[0].regionId, 'ERCO');
assert.deepEqual(cases[0].result.comparison.savings, { costUsd: 0, carbonKg: 60, costPercent: 0, carbonPercent: 75 });
assert.deepEqual(cases[1].result.comparison.savings, { costUsd: 0, carbonKg: 0, costPercent: 0, carbonPercent: 0 });
assert.equal(cases[2].result.comparison.savings.costUsd, -20);
assert.equal(cases[3].result.policies.regionAndTime.assignments[0].regionId, 'CISO');
assert.equal(cases[4].result.policies.regionAndTime.unplaced[0].reason, 'NO_FEASIBLE_WINDOW');
assert.equal(cases[4].result.comparison.reason, 'NO_COMPLETED_WORK');
const historical = planScenario(snapshot);
const report = { description: 'Four teaching situations, including both objectives for the tradeoff. All teaching inputs are synthetic. Results are generated by the public planner.',
  teachingProvenance: 'Hand-authored controls: carbon is 400 g/kWh except ERCO at 100; prices are 100 USD/MWh except ERCO at 200 in tradeoff cases. priceSeed 4271 is inherited base-snapshot metadata, not the recipe for these overrides. Capacities are 32 or explicitly zero; jobs are hand-authored.', cases,
  historicalSummary: { scenarioId: historical.scenarioId, input: 'data/scenario.json', policies: Object.fromEntries(Object.entries(historical.policies).map(([id, p]) => [id, { totals: p.totals, counts: p.counts, assignments: p.assignments.map(({ alternatives, ...assignment }) => assignment), unplaced: p.unplaced }])), comparison: historical.comparison },
};
writeFileSync(path.join(__dirname, '../examples/p2-worked-examples.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report.historicalSummary, null, 2));
console.log('Four worked situations verified and saved to examples/p2-worked-examples.json.');
